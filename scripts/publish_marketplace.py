#!/usr/bin/env python3
"""Publish the client-install artifacts into the public marketplace repository.

Two channels install this service, and both hardcode an endpoint:

* the **Gemini CLI extension** - `gemini-extension.json` plus its `GEMINI.md` context file,
* the **Claude Code plugin** - `plugins/financial-portfolios/.mcp.json`.

They live in a public repository because `gemini extensions install` and
`/plugin marketplace add` both clone one, while this repository is private. That split is
how they drift: a published artifact can quietly point at an environment nobody is running.

So the environment is a parameter, never a hand edit:

    python scripts/publish_marketplace.py --env dev
    python scripts/publish_marketplace.py --env prod
    python scripts/publish_marketplace.py --env dev --check    # verify, change nothing

**The target is probed before anything is written.** A `POST /mcp` with no credential must
answer `401` with an RFC 9728 challenge - that is a live MCP server. Publishing against
`https://financial-portfolios.ai` once produced artifacts that installed cleanly and then
returned `404` on every call, because the apex domain serves a placeholder page; the probe
is what stops that reaching a customer. `--no-verify` skips it, for an environment that is
not up yet.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from financial_portfolios_ai_mcp.manifests import (
    ENVIRONMENTS,
    PLACEHOLDER,
    render,
)

GEMINI_MANIFEST = "gemini-extension.json"
GEMINI_CONTEXT = "GEMINI.md"
PLUGIN_CONFIG = Path("plugins/financial-portfolios/.mcp.json")


MARKETPLACE_REPO = "financial-portfolios-ai-marketplace"


def find_marketplace() -> Path | None:
    """Locate the public checkout beside this one.

    Walks upward rather than assuming a fixed depth: this repository is often checked out as
    a git worktree, where the sibling is several levels above the working directory.
    """
    for parent in [REPO_ROOT, *REPO_ROOT.parents]:
        candidate = parent.parent / MARKETPLACE_REPO
        if (candidate / PLUGIN_CONFIG).is_file():
            return candidate
    return None

# The plugin's URL is an env-var default inside a JSON string, so it is rewritten by pattern
# rather than by key: `${FINANCIAL_PORTFOLIOS_MCP_URL:-https://.../mcp}` keeps the user's override working.
PLUGIN_URL_PATTERN = re.compile(r"(\$\{FINANCIAL_PORTFOLIOS_MCP_URL:-)(https?://[^}]+)(\})")


def probe(origin: str) -> tuple[bool, str]:
    """Is a real MCP server answering at this origin?

    A tokenless `POST /mcp` must be challenged with `401`. A `404` means nothing is mounted
    there; a `200` would mean the endpoint is unauthenticated, which is equally wrong.
    """
    request = urllib.request.Request(
        f"{origin}/mcp",
        data=b"{}",
        headers={"Content-Type": "application/json", "Accept": "application/json, text/event-stream"},
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return False, f"POST /mcp returned {response.status}; expected a 401 challenge"
    except urllib.error.HTTPError as error:
        if error.code != 401:
            return False, f"POST /mcp returned {error.code}; expected 401 (nothing is served there)"
        challenge = error.headers.get("WWW-Authenticate") or ""
        if "resource_metadata" not in challenge:
            return False, f"401 carries no resource_metadata challenge: {challenge or 'no header'}"
        return True, "401 with an RFC 9728 challenge"
    except (urllib.error.URLError, OSError) as error:
        return False, f"unreachable: {error}"


def gemini_manifest(origin: str, env: str | None) -> str:
    manifest = render(GEMINI_MANIFEST, origin)
    note = (
        f"Generated by scripts/publish_marketplace.py for the {env or origin} deployment "
        f"({origin}). Do not edit here - edit the template in the financial-portfolios-ai-mcp "
        f"repository and re-publish."
    )
    if env != "prod":
        note += " This is not the production deployment."
    return json.dumps({"$comment": note, **manifest}, indent=2, ensure_ascii=False) + "\n"


def gemini_context(origin: str, env: str | None) -> str:
    text = (REPO_ROOT / GEMINI_CONTEXT).read_text(encoding="utf-8").replace(PLACEHOLDER, origin)
    # Strip the template's own editing note; it is meaningless in the published copy.
    text = re.sub(r"^<!-- Template:.*?-->\n", "", text, count=1, flags=re.DOTALL)
    if env != "prod":
        text = text.replace(
            "# Financial Portfolios AI\n",
            "# Financial Portfolios AI\n\n> **Preview.** This extension connects to the "
            f"**{env or 'non-production'}** deployment; the production domain does not serve "
            "the MCP endpoint yet.\n",
            1,
        )
    return text


def plugin_config(current: str, origin: str) -> str:
    replaced, count = PLUGIN_URL_PATTERN.subn(rf"\g<1>{origin}/mcp\g<3>", current)
    if count != 1:
        raise SystemExit(
            f"Expected exactly one ${{FINANCIAL_PORTFOLIOS_MCP_URL:-...}} default in {PLUGIN_CONFIG}, found {count}. "
            "The plugin's config shape changed; update this script rather than editing by hand."
        )
    return replaced


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--env", choices=sorted(ENVIRONMENTS), help="Deployment to publish for.")
    target.add_argument("--origin", help="Explicit origin, e.g. https://staging.financial-portfolios.ai")
    parser.add_argument(
        "--marketplace",
        type=Path,
        default=None,
        help=f"Checkout of the public {MARKETPLACE_REPO} repository (default: found beside this one).",
    )
    parser.add_argument("--check", action="store_true", help="Report differences and write nothing.")
    parser.add_argument("--no-verify", action="store_true", help="Skip the live endpoint probe.")
    args = parser.parse_args(argv)

    origin = (args.origin or ENVIRONMENTS[args.env]).rstrip("/")
    if not origin.startswith(("http://", "https://")):
        parser.error("--origin must include the scheme, e.g. https://dev.financial-portfolios.ai")
    marketplace = args.marketplace or find_marketplace()
    if marketplace is None:
        parser.error(f"Could not find a {MARKETPLACE_REPO} checkout beside this one; pass --marketplace")
    if not (marketplace / PLUGIN_CONFIG).is_file():
        parser.error(f"{marketplace} does not look like the marketplace checkout ({PLUGIN_CONFIG} missing)")

    print(f"Target: {origin}" + (f"  ({args.env})" if args.env else ""))
    if args.no_verify:
        print("  probe: skipped")
    else:
        ok, detail = probe(origin)
        print(f"  probe: {detail}")
        if not ok:
            print(
                "\nRefusing to publish: nothing is serving MCP at that origin, so every install "
                "would fail on its first call. Re-run with --no-verify only if you are publishing "
                "ahead of a deployment on purpose.",
                file=sys.stderr,
            )
            return 1

    plugin_path = marketplace / PLUGIN_CONFIG
    wanted = {
        marketplace / GEMINI_MANIFEST: gemini_manifest(origin, args.env),
        marketplace / GEMINI_CONTEXT: gemini_context(origin, args.env),
        plugin_path: plugin_config(plugin_path.read_text(encoding="utf-8"), origin),
    }

    changed = []
    for path, content in wanted.items():
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        if existing == content:
            print(f"  unchanged  {path.relative_to(marketplace)}")
            continue
        changed.append(path)
        if args.check:
            print(f"  DIFFERS    {path.relative_to(marketplace)}")
        else:
            path.write_text(content, encoding="utf-8")
            print(f"  written    {path.relative_to(marketplace)}")

    if args.check and changed:
        print(f"\n{len(changed)} file(s) differ from what --env {args.env or origin} would publish.", file=sys.stderr)
        return 1
    if not changed:
        print("\nAlready up to date.")
    else:
        print(f"\n{len(changed)} file(s) written. Review and commit in {marketplace}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
